// Generates the platform files from src/tokens.ts so tokens are defined once.
//   web.css              -> Tailwind v4 / shadcn CSS variables (apps/web imports it)
//   tailwind-preset.cjs  -> Tailwind v3 preset (NativeWind in apps/mobile)
// Run: pnpm --filter @bhw/design-tokens build  (Node >= 22.18 strips TS types natively)
import { writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { dirname, join } from "node:path";
import { colors, statusColors, radius, typography } from "../src/tokens.ts";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const kebab = (s) => s.replace(/[A-Z]/g, (m) => `-${m.toLowerCase()}`);

const vars = (scheme) =>
  Object.entries(scheme)
    .map(([k, v]) => `  --${kebab(k)}: ${v};`)
    .join("\n");

const statusVars = Object.entries(statusColors)
  .map(
    ([k, v]) =>
      `  --status-${k.replace("_", "-")}-bg: ${v.bg};\n  --status-${k.replace("_", "-")}-fg: ${v.fg};`,
  )
  .join("\n");

const themeColorKeys = Object.keys(colors.light);
const themeInline = [
  ...themeColorKeys.map((k) => `  --color-${kebab(k)}: var(--${kebab(k)});`),
  ...Object.keys(statusColors).flatMap((k) => {
    const n = k.replace("_", "-");
    return [
      `  --color-status-${n}: var(--status-${n}-bg);`,
      `  --color-status-${n}-foreground: var(--status-${n}-fg);`,
    ];
  }),
  `  --radius-sm: ${radius.control - 2}px;`,
  `  --radius-md: ${radius.control}px;`,
  `  --radius-lg: ${radius.control + 2}px;`,
  `  --radius-xl: ${radius.cardWeb}px;`,
  `  --radius-2xl: ${radius.cardMobile}px;`,
  `  --font-sans: var(--font-inter), ${typography.fontFamilyFallback.map((f) => (f.includes(" ") ? `"${f}"` : f)).join(", ")};`,
].join("\n");

const css = `/* GENERATED by packages/design-tokens/scripts/generate.mjs - do not edit by hand. */
:root {
  --radius: ${radius.control}px;
${vars(colors.light)}
${statusVars}
  --chart-1: #0f766e;
  --chart-2: #f59e0b;
  --chart-3: #ef4444;
  --chart-4: #71717a;
  --chart-5: #ea580c;
}

.dark {
${vars(colors.dark)}
  --chart-1: #14b8a6;
  --chart-2: #fbbf24;
  --chart-3: #f87171;
  --chart-4: #a1a1aa;
  --chart-5: #fb923c;
}

@theme inline {
${themeInline}
  --color-chart-1: var(--chart-1);
  --color-chart-2: var(--chart-2);
  --color-chart-3: var(--chart-3);
  --color-chart-4: var(--chart-4);
  --color-chart-5: var(--chart-5);
}
`;

const preset = `// GENERATED by packages/design-tokens/scripts/generate.mjs - do not edit by hand.
// Tailwind v3 preset for NativeWind. Light values are defaults; dark values are applied with
// NativeWind's vars() in apps/mobile/lib/theme.ts using \`colorsDark\`.
/** @type {import('tailwindcss').Config} */
const colorsLight = ${JSON.stringify(colors.light, null, 2)};
const colorsDark = ${JSON.stringify(colors.dark, null, 2)};
const status = ${JSON.stringify(Object.fromEntries(Object.entries(statusColors).map(([k, v]) => [k, { bg: v.bg, fg: v.fg }])), null, 2)};

const kebab = (s) => s.replace(/[A-Z]/g, (m) => "-" + m.toLowerCase());
const cssVarColors = Object.fromEntries(
  Object.keys(colorsLight).map((k) => [kebab(k), "rgb(var(--" + kebab(k) + ") / <alpha-value>)"]),
);

module.exports = {
  colorsLight,
  colorsDark,
  theme: {
    extend: {
      colors: {
        ...cssVarColors,
        status: Object.fromEntries(
          Object.entries(status).flatMap(([k, v]) => [
            [k.replace("_", "-"), v.bg],
            [k.replace("_", "-") + "-foreground", v.fg],
          ]),
        ),
      },
      borderRadius: {
        DEFAULT: "${radius.control}px",
        md: "${radius.control}px",
        xl: "${radius.cardWeb}px",
        "2xl": "${radius.cardMobile}px",
        full: "9999px",
      },
      fontFamily: {
        sans: ["${typography.mobileFonts.regular}"],
        medium: ["${typography.mobileFonts.medium}"],
        semibold: ["${typography.mobileFonts.semibold}"],
        bold: ["${typography.mobileFonts.bold}"],
      },
      minHeight: { touch: "44px" },
      minWidth: { touch: "44px" },
    },
  },
};
`;

writeFileSync(join(root, "web.css"), css);
writeFileSync(join(root, "tailwind-preset.cjs"), preset);
console.log("design-tokens: wrote web.css and tailwind-preset.cjs");
