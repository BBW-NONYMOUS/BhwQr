#!/usr/bin/env node
// Generates apps/mobile/global.css from @bhw/design-tokens so the palette stays single-source.
//
// The design-tokens Tailwind preset maps every color to `rgb(var(--<token>) / <alpha-value>)`,
// so NativeWind needs each token as a space-separated RGB triplet ("15 118 110"):
//   :root  -> light values      .dark -> dark values (NativeWind toggles the class from useColorScheme)
//
// Run: pnpm --filter @bhw/mobile gen:css   (re-run after changing packages/design-tokens)
import { createRequire } from "node:module";
import { writeFileSync, readFileSync, existsSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { dirname, join } from "node:path";

const require = createRequire(import.meta.url);
const { colorsLight, colorsDark } = require("@bhw/design-tokens/tailwind-preset");

const here = dirname(fileURLToPath(import.meta.url));
const out = join(here, "..", "global.css");

const kebab = (s) => s.replace(/[A-Z]/g, (m) => "-" + m.toLowerCase());

function hexToTriplet(hex) {
  const h = hex.replace("#", "");
  const full = h.length === 3 ? h.split("").map((c) => c + c).join("") : h;
  if (!/^[0-9a-fA-F]{6}$/.test(full)) throw new Error(`Unsupported color "${hex}" (expected #rgb or #rrggbb)`);
  const n = parseInt(full, 16);
  return `${(n >> 16) & 255} ${(n >> 8) & 255} ${n & 255}`;
}

function block(selector, colors) {
  const lines = Object.entries(colors).map(([k, v]) => `    --${kebab(k)}: ${hexToTriplet(v)}; /* ${v} */`);
  return `  ${selector} {\n${lines.join("\n")}\n  }`;
}

const missing = Object.keys(colorsLight).filter((k) => !(k in colorsDark));
if (missing.length) throw new Error(`Dark palette is missing tokens: ${missing.join(", ")}`);

const css = `/* GENERATED by apps/mobile/scripts/gen-css-vars.mjs from @bhw/design-tokens - do not edit by hand. */
@tailwind base;
@tailwind components;
@tailwind utilities;

@layer base {
${block(":root", colorsLight)}

${block(".dark:root", colorsDark)}
}
`;

const previous = existsSync(out) ? readFileSync(out, "utf8") : "";
if (previous !== css) {
  writeFileSync(out, css);
  console.log(`global.css written (${Object.keys(colorsLight).length} tokens x 2 themes)`);
} else {
  console.log("global.css already up to date");
}
