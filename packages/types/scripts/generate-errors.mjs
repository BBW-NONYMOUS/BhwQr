// Generates src/errors.generated.ts and supabase/functions/_shared/error-codes.generated.ts
// from the error-code catalog (Tables E-1..E-3) in docs/phase-1-system-analysis/05-business-rules.md.
// The catalog document is the single source of truth for codes, HTTP status and EN/FIL messages.
// Run: pnpm --filter @bhw/types gen:errors
import { readFileSync, writeFileSync, mkdirSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { dirname, join } from "node:path";

const pkg = join(dirname(fileURLToPath(import.meta.url)), "..");
const repo = join(pkg, "..", "..");
const md = readFileSync(join(repo, "docs/phase-1-system-analysis/05-business-rules.md"), "utf8");

const section = md.slice(md.indexOf("## 15. Error-code catalog"));
const rows = [];
let table = "";
for (const line of section.split(/\r?\n/)) {
  const t = line.match(/^### Table (E-\d)/);
  if (t) table = t[1];
  const m = line.match(/^\| `([A-Z_]+)` \| ([^|]+) \| ([^|]+) \| ([^|]+) \| ([^|]+) \|$/);
  if (m && table) {
    const http = m[2].trim();
    rows.push({
      code: m[1],
      http: /^\d+$/.test(http) ? Number(http) : null,
      group: table === "E-1" ? "scan" : table === "E-2" ? "client" : "general",
      en: m[4].trim(),
      fil: m[5].trim(),
    });
  }
}
if (rows.length !== 39) {
  throw new Error(`Expected 39 error codes in the catalog, found ${rows.length}`);
}

const banner =
  "// GENERATED by packages/types/scripts/generate-errors.mjs from\n" +
  "// docs/phase-1-system-analysis/05-business-rules.md section 15. Do not edit by hand.\n";

const entries = rows
  .map(
    (r) =>
      `  ${r.code}: {\n    http: ${r.http},\n    group: ${JSON.stringify(r.group)},\n    en: ${JSON.stringify(r.en)},\n    fil: ${JSON.stringify(r.fil)},\n  },`,
  )
  .join("\n");

const body = `${banner}
export const ERROR_CATALOG = {
${entries}
} as const;

export type ErrorCode = keyof typeof ERROR_CATALOG;

/** Codes the server may store in scan_attempts.error_code (Table E-1, validation order). */
export const SCAN_ERROR_CODES = [
${rows
  .filter((r) => r.group === "scan")
  .map((r) => `  ${JSON.stringify(r.code)},`)
  .join("\n")}
] as const;
export type ScanErrorCode = (typeof SCAN_ERROR_CODES)[number];

/** Mobile-only pre-scan codes (Table E-2); never sent to the server. */
export const CLIENT_ERROR_CODES = [
${rows
  .filter((r) => r.group === "client")
  .map((r) => `  ${JSON.stringify(r.code)},`)
  .join("\n")}
] as const;
export type ClientErrorCode = (typeof CLIENT_ERROR_CODES)[number];
`;

writeFileSync(join(pkg, "src/errors.generated.ts"), body);
const fnShared = join(repo, "supabase/functions/_shared");
mkdirSync(fnShared, { recursive: true });
writeFileSync(join(fnShared, "error-codes.generated.ts"), body);
console.log(`types: wrote ${rows.length} error codes`);
