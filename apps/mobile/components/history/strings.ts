/** Catalog message for a code, plus the few app-only codes these screens raise. */
export function friendlyError(code: string, lang: Lang, params: Record<string, string | number> = {}): string {
  if (code === "ATTACHMENT_UNREADABLE") return L[lang].attachmentUnreadable;
  if (code === "SHARING_UNAVAILABLE") return L[lang].sharingUnavailable;
  return errorMessage(code, lang, params);
}

